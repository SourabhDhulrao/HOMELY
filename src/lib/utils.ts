import { clsx, type ClassValue } from "clsx";
import { twMerge } from "tailwind-merge";

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs));
}

/**
 * Format Indian Rupee currency (e.g. ₹999 or ₹1,499)
 */
export function formatINR(amount: number | null | undefined): string {
  if (amount === null || amount === undefined || isNaN(amount)) {
    return "";
  }
  return new Intl.NumberFormat("en-IN", {
    style: "currency",
    currency: "INR",
    maximumFractionDigits: 0,
  }).format(amount);
}

/**
 * Validate that a URL is an authorized Amazon India destination
 * Allowed domains: amazon.in, *.amazon.in, amzn.to, amzn.in
 */
export function isValidAmazonIndiaUrl(urlString: string): boolean {
  if (!urlString || typeof urlString !== 'string') return false;
  const trimmed = urlString.trim();
  if (!trimmed) return false;

  try {
    const url = new URL(trimmed);
    if (url.protocol !== 'https:' && url.protocol !== 'http:') return false;
    const hostname = url.hostname.toLowerCase();
    return (
      hostname === 'amazon.in' ||
      hostname.endsWith('.amazon.in') ||
      hostname === 'amzn.to' ||
      hostname.endsWith('.amzn.to') ||
      hostname === 'amzn.in' ||
      hostname.endsWith('.amzn.in')
    );
  } catch {
    return false;
  }
}

/**
 * Ensure Amazon India URL has the official affiliate tracking tag attached.
 * Preserves exact affiliate URLs and shortened links (amzn.to) without destroying parameters.
 */
export function buildAmazonAffiliateUrl(rawUrl: string, asin?: string): string {
  const partnerTag = process.env.NEXT_PUBLIC_AMAZON_PARTNER_TAG || "homelyindia-21";
  
  if (!rawUrl && asin) {
    return `https://www.amazon.in/dp/${asin}?tag=${partnerTag}`;
  }

  if (!rawUrl) return '';

  const trimmed = rawUrl.trim();

  try {
    const url = new URL(trimmed);
    // If it's a shortened link (amzn.to, amzn.in), preserve it exactly as generated by Amazon Associates / SiteStripe
    if (url.hostname.includes('amzn.to') || url.hostname.includes('amzn.in')) {
      return trimmed;
    }
    // If it's standard amazon.in, ensure the associate tracking tag is present
    if (url.hostname.includes('amazon.in')) {
      if (!url.searchParams.get("tag")) {
        url.searchParams.set("tag", partnerTag);
      }
      return url.toString();
    }
    return trimmed;
  } catch {
    if (asin) {
      return `https://www.amazon.in/dp/${asin}?tag=${partnerTag}`;
    }
    return trimmed;
  }
}

/**
 * Generate Pinterest Pin URL for viral discovery
 */
export function buildPinterestPinUrl(params: {
  url: string;
  media: string;
  description: string;
}): string {
  const base = "https://pinterest.com/pin/create/button/";
  const searchParams = new URLSearchParams({
    url: params.url,
    media: params.media,
    description: `${params.description} — Discovered on HOMELY (homelyliving.in)`,
  });
  return `${base}?${searchParams.toString()}`;
}

export function slugify(text: string): string {
  return text
    .toString()
    .toLowerCase()
    .trim()
    .replace(/\s+/g, "-")
    .replace(/[^\w-]+/g, "")
    .replace(/--+/g, "-")
    .replace(/^-+/, "")
    .replace(/-+$/, "");
}

